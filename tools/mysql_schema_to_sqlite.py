#!/usr/bin/env python3
"""Turn `mysqldump --no-data --compact` output for the SCS tables into SQLite DDL.

    mysqldump --no-data --skip-comments --skip-add-drop-table --compact DB TABLES... \\
        | tools/mysql_schema_to_sqlite.py --skip user log > rust/migrations/0002_legacy_tables.sql

Column types become SQLite affinities, not STRICT types, because the MySQL data holds legacy values (empty strings in
integer columns, zero dates) that STRICT would refuse. Keys become indexes named <table>_<key>. Tables named by
--skip are left to a hand-written migration.
"""
import argparse
import re
import sys

INTEGER = {"tinyint", "smallint", "mediumint", "int", "integer", "bigint", "bit", "boolean"}
REAL = {"decimal", "numeric", "float", "double", "real"}
BLOB = {"blob", "tinyblob", "mediumblob", "longblob", "binary", "varbinary"}


def affinity(mysql_type):
    base = re.match(r"[a-z]+", mysql_type.lower()).group(0)
    if base in INTEGER:
        return "INTEGER"
    if base in REAL:
        return "REAL"
    if base in BLOB:
        return "BLOB"
    return "TEXT"


def columns_of(spec):
    return [c.strip().strip("`") for c in re.findall(r"`[^`]+`(?:\(\d+\))?", spec)]


def convert(table, body):
    cols, keys, primary = [], [], None
    auto_col = None
    for raw in body:
        line = raw.strip().rstrip(",")
        m = re.match(r"PRIMARY KEY \((.*)\)", line)
        if m:
            primary = columns_of(m.group(1))
            continue
        m = re.match(r"(UNIQUE )?(?:KEY|INDEX) `([^`]+)` \((.*)\)", line)
        if m:
            keys.append((bool(m.group(1)), m.group(2), columns_of(m.group(3))))
            continue
        if re.match(r"(FULLTEXT|SPATIAL|CONSTRAINT|FOREIGN)", line):
            continue
        m = re.match(r"`([^`]+)` (\w+(?:\([^)]*\))?)(.*)", line)
        if not m:
            raise SystemExit(f"{table}: cannot read column line: {line!r}")
        name, mysql_type, rest = m.groups()
        parts = [affinity(mysql_type)]
        if "NOT NULL" in rest:
            parts.append("NOT NULL")
        d = re.search(r"DEFAULT ('(?:[^']|'')*'|-?[\d.]+|NULL)", rest)
        if d and d.group(1) != "NULL":
            parts.append("DEFAULT " + d.group(1))
        if "AUTO_INCREMENT" in rest:
            auto_col = name
        cols.append((name, parts))
    out = []
    for name, parts in cols:
        if name == auto_col and primary == [name]:
            out.append(f'  "{name}" INTEGER PRIMARY KEY')
        else:
            out.append(f'  "{name}" ' + " ".join(parts))
    if primary and not (auto_col and primary == [auto_col]):
        out.append("  PRIMARY KEY (" + ", ".join(f'"{c}"' for c in primary) + ")")
    ddl = [f'CREATE TABLE "{table}" (\n' + ",\n".join(out) + "\n);"]
    for unique, key, key_cols in keys:
        kind = "UNIQUE INDEX" if unique else "INDEX"
        ddl.append(f'CREATE {kind} "{table}_{key}" ON "{table}" (' + ", ".join(f'"{c}"' for c in key_cols) + ");")
    return "\n".join(ddl)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--skip", nargs="*", default=[])
    args = ap.parse_args()
    text = sys.stdin.read()
    print("-- Generated by tools/mysql_schema_to_sqlite.py from the production MySQL schema. Do not edit by hand.")
    for m in re.finditer(r"CREATE TABLE `([^`]+)` \((.*?)\n\)[^;]*;", text, re.S):
        table, body = m.group(1), m.group(2).split("\n")
        if table in args.skip:
            continue
        print()
        print(convert(table, [b for b in body if b.strip()]))


if __name__ == "__main__":
    main()
