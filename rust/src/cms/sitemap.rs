//! Yoast SEO's XML sitemaps, from the cms content as WPML shows it in the request's language, for what the site still
//! has: the pages, the FAQs and the FAQ types, listed in sitemap_index.xml.

use std::fmt::Write;

use super::{
    html::decode_attr,
    model::{Lang, Page, PostType, Site, Status, Taxonomy},
    theme::{ORIGIN, UPLOADS},
    yoast,
};

const XSL_EN: &str = "//www.harcourt.co/wp-content/plugins/wordpress-seo/css/main-sitemap.xsl";
const XSL_FR: &str = "//www.harcourt.co/main-sitemap.xsl?lang=fr";
const URLSET: &str = "<urlset xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\" xmlns:image=\"http://www.google.com/schemas/sitemap-image/1.1\" xsi:schemaLocation=\"http://www.sitemaps.org/schemas/sitemap/0.9 http://www.sitemaps.org/schemas/sitemap/0.9/sitemap.xsd http://www.google.com/schemas/sitemap-image/1.1 http://www.google.com/schemas/sitemap-image/1.1/sitemap-image.xsd\" xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n";
const SIGNATURE: &str = "<!-- XML Sitemap generated by Yoast SEO -->";

/// The sitemap XSL Yoast serves at /main-sitemap.xsl.
pub const XSL: &str = include_str!("../../assets/main-sitemap.xsl");

/// One sitemap of the index, by the name in its URL (`page` for /page-sitemap.xml).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Map {
    Pages,
    Faqs,
    FaqTypes,
}

impl Map {
    pub fn parse(name: &str) -> Option<Map> {
        match name {
            "page" => Some(Map::Pages),
            "faq" => Some(Map::Faqs),
            "faq_type" => Some(Map::FaqTypes),
            _ => None,
        }
    }

    fn name(self) -> &'static str {
        match self {
            Map::Pages => "page",
            Map::Faqs => "faq",
            Map::FaqTypes => "faq_type",
        }
    }
}

struct Url {
    loc: String,
    lastmod: String,
    images: Vec<String>,
}

/// `2019-11-19 20:06:55` (GMT) as Yoast prints it.
fn iso(gmt: &str) -> String {
    format!("{}+00:00", gmt.replacen(' ', "T", 1))
}

fn head(lang: Lang) -> String {
    let xsl = if lang == Lang::Fr { XSL_FR } else { XSL_EN };
    format!("<?xml version=\"1.0\" encoding=\"UTF-8\"?><?xml-stylesheet type=\"text/xsl\" href=\"{xsl}\"?>\n")
}

fn indexed(p: &Page) -> bool {
    p.status == Status::Publish
}

/// The sitemaps the index lists, in Yoast's order, each with its lastmod.
fn maps(site: &Site, lang: Lang) -> Vec<(Map, String)> {
    let mut out = Vec::new();
    for (map, t) in [(Map::Pages, PostType::Page), (Map::Faqs, PostType::Faq)] {
        if yoast::type_noindex(site, t) {
            continue;
        }
        if let Some(m) = site.pages.iter().filter(|p| p.kind == t && indexed(p)).map(|p| p.modified_at.as_str()).max() {
            out.push((map, iso(m)));
        }
    }
    if !yoast::taxonomy_noindex(site, Taxonomy::FaqType) && terms(site, Taxonomy::FaqType, lang).next().is_some() {
        let m = site.pages.iter().filter(|p| p.kind == PostType::Faq && p.lang == lang && indexed(p)).map(|p| p.modified_at.as_str()).max().unwrap_or("");
        out.push((Map::FaqTypes, iso(m)));
    }
    out
}

/// The terms of a taxonomy WPML shows in `lang` that file a published post: its terms in that language, or all of
/// them when none is translated into it.
fn terms(site: &Site, taxonomy: Taxonomy, lang: Lang) -> impl Iterator<Item = &super::model::Term> {
    let translated = site.terms.iter().any(|t| t.taxonomy == taxonomy && t.lang == Some(lang));
    site.terms.iter().filter(move |t| {
        t.taxonomy == taxonomy
            && (!translated || t.lang == Some(lang))
            && t.pages.iter().any(|id| site.page(*id).is_some_and(|p| indexed(p) && p.kind == taxonomy.of()))
    })
}

/// sitemap_index.xml in `lang`.
pub fn index(site: &Site, lang: Lang) -> String {
    let mut out = head(lang);
    out.push_str("<sitemapindex xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n");
    for (map, lastmod) in maps(site, lang) {
        let _ = write!(out, "\t<sitemap>\n\t\t<loc>{ORIGIN}{}</loc>\n\t\t<lastmod>{lastmod}</lastmod>\n\t</sitemap>\n", lang.link(&format!("/{}-sitemap.xml", map.name())));
    }
    out.push_str("</sitemapindex>\n");
    out.push_str(SIGNATURE);
    out
}

/// One sitemap in `lang`, or None when the index does not list it.
pub fn urlset(site: &Site, map: Map, lang: Lang) -> Option<String> {
    if !maps(site, lang).iter().any(|(m, _)| *m == map) {
        return None;
    }
    let urls = match map {
        Map::Pages => posts(site, PostType::Page, lang),
        Map::Faqs => posts(site, PostType::Faq, lang),
        Map::FaqTypes => terms(site, Taxonomy::FaqType, lang)
            .map(|t| Url { loc: format!("{ORIGIN}{}", t.lang.map_or_else(|| t.path(), |l| l.link(&t.path()))), lastmod: iso(&t.modified_at), images: Vec::new() })
            .collect(),
    };
    let mut out = head(lang);
    out.push_str(URLSET);
    for u in urls {
        let _ = write!(out, "\t<url>\n\t\t<loc>{}</loc>\n\t\t<lastmod>{}</lastmod>\n", xml(&u.loc), u.lastmod);
        for i in &u.images {
            let _ = write!(out, "\t\t<image:image>\n\t\t\t<image:loc>{}</image:loc>\n\t\t</image:image>\n", xml(i));
        }
        out.push_str("\t</url>\n");
    }
    out.push_str("</urlset>\n");
    out.push_str(SIGNATURE);
    Some(out)
}

/// A post type's published posts by last change, each at the URL WPML gives it in `lang` (its translation's, which
/// lists a French page under its English URL in English), with the front page first for pages.
fn posts(site: &Site, t: PostType, lang: Lang) -> Vec<Url> {
    let front = site.find(lang, "/").filter(|_| t == PostType::Page);
    let mut list: Vec<&Page> = site.pages.iter().filter(|p| p.kind == t && indexed(p) && !yoast::noindex(site, p) && Some(p.id) != front.map(|f| f.id)).collect();
    list.sort_by(|a, b| (a.modified_at.as_str(), a.id).cmp(&(b.modified_at.as_str(), b.id)));
    let url = |p: &Page| match site.translation(p, lang) {
        Some(t) => t.url(ORIGIN),
        None => p.url(ORIGIN),
    };
    front.into_iter().chain(list).map(|p| Url { loc: url(p), lastmod: iso(&p.modified_at), images: images(site, p) }).collect()
}

/// WPSEO_Sitemap_Image_Parser: the featured image, then every image in the post content, as the site links them.
fn images(site: &Site, p: &Page) -> Vec<String> {
    let mut out = Vec::new();
    let fields = site.fields(p.id);
    if let Some(m) = fields.get("@thumbnail").and_then(|f| f.value.trim().parse::<i64>().ok()).and_then(|id| site.media.get(&super::model::MediaId(id))) {
        out.push(format!("{UPLOADS}{}", m.file));
    }
    let content = fields.get("content").map(|f| f.value.as_str()).unwrap_or("");
    let mut rest = content;
    while let Some(i) = rest.find("<img") {
        rest = &rest[i + 4..];
        let tag = &rest[..rest.find('>').unwrap_or(rest.len())];
        if let Some(src) = attr(tag, "src").map(decode_attr) {
            let src = if src.starts_with('/') && !src.starts_with("//") { format!("{ORIGIN}{src}") } else { src.to_string() };
            if src.contains("www.harcourt.co/") {
                out.push(src);
            }
        }
    }
    out
}

/// A URL as Yoast's encode_and_escape() writes it into the XML, `&` as `&amp;` and `'` as `&apos;`.
fn xml(url: &str) -> String {
    let mut out = String::with_capacity(url.len());
    for c in url.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '\'' => out.push_str("&apos;"),
            '"' => out.push_str("&quot;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            c => out.push(c),
        }
    }
    out
}

/// The value of attribute `name` as an HTML parser reads it: up to the closing quote, or unquoted up to whitespace.
fn attr<'a>(tag: &'a str, name: &str) -> Option<&'a str> {
    let at = tag.find(&format!(" {name}="))? + name.len() + 2;
    let value = &tag[at..];
    match value.chars().next()? {
        quote @ ('"' | '\'') => {
            let rest = &value[1..];
            Some(&rest[..rest.find(quote)?])
        }
        _ => value.split(|c: char| c.is_ascii_whitespace()).next(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dates_print_as_yoast_prints_them() {
        assert_eq!(iso("2019-11-19 20:06:55"), "2019-11-19T20:06:55+00:00");
        assert_eq!(attr(" src=\"/a.png\" alt=''", "src"), Some("/a.png"));
        assert_eq!(attr(" alt='' src=/a.png", "src"), Some("/a.png"));
        assert_eq!(attr(" src=\u{201c}/a.png\u{201d} alt=x", "src"), Some("\u{201c}/a.png\u{201d}"));
        assert_eq!(attr(" src=\"/a.png", "src"), None);
        assert_eq!(xml(&decode_attr("https://www.harcourt.co/a.png?w=1&amp;h=2&q=R&D's")), "https://www.harcourt.co/a.png?w=1&amp;h=2&amp;q=R&amp;D&apos;s");
        assert!(head(Lang::Fr).contains("type=\"text/xsl\" href=\"//www.harcourt.co/main-sitemap.xsl?lang=fr\"?>\n"));
        assert_eq!(Map::parse("faq_type"), Some(Map::FaqTypes));
        assert_eq!(Map::parse("page"), Some(Map::Pages));
        for dropped in ["post", "case_study", "category", "author", "nosuch"] {
            assert_eq!(Map::parse(dropped), None, "{dropped}");
        }
    }

    #[test]
    fn a_draft_translation_is_listed_at_its_page_id_link() {
        let page = |id: i64, lang: Lang, path: &str, status: Status| Page {
            id: super::super::model::PageId(id),
            kind: PostType::Page,
            name: String::new(),
            group_id: 10,
            lang,
            path: path.into(),
            template: super::super::model::Template::Page,
            status,
            title: String::new(),
            parent_id: None,
            menu_order: 0,
            published_at: "2020-01-01 00:00:00".into(),
            modified_at: "2020-01-01 00:00:00".into(),
            author_id: None,
        };
        let site = Site::new(vec![page(10, Lang::En, "/tooling/", Status::Publish), page(11, Lang::Fr, "/?page_id=11", Status::Draft)]);
        let fr = urlset(&site, Map::Pages, Lang::Fr).unwrap();
        assert!(fr.contains("<loc>https://www.harcourt.co/?page_id=11&amp;lang=fr</loc>"), "{fr}");
        let en = urlset(&site, Map::Pages, Lang::En).unwrap();
        assert!(en.contains("<loc>https://www.harcourt.co/tooling/</loc>"), "{en}");
    }
}
